{'        ,@@@@@@@@@@*   ##(###  #   (##     #((,   '},...
{'      #* @@@@@@@@,@     ((((#     #(#/   ##((#    '},...
{'     (             @  ((((( #    #(#    /# (#     '},...
{'    #               #((((#      #(#(       /#     '},...
{'   #(          ##((((##@     #(##      ##         '},...
{'  .###,  ,###((((##     @ (#(##     #(((#         '},...
{'  #. *##((###*         *#((#      #(((#*          '},...
{'  (#                ##((#/ @   ,#(((#             '},...
{'  #(#.         (##((##      @##((##               '},...
{' * (#((((((((((###         ##((#*                 '},...
{' #                       ##(##. @                 '},...
{' #;                .(#((##       @                '},...
{'  (#&         # ##(##(            @&       @      '},...
{'   /######(#(###.                   @       @,    '},...
{'                                     &@*   @@     '},...
{'                                       .@@.#      '}];
                                                 

txt =[...
{'               &&&&        &&&&   ,&&&&&&&&&&  '},...
{'               &&.&&      &&,&&   ,&&      &&  '},...
{'   .&&%,&&&&   &&. &&    *&% &&   ,&&    *&&*  '},...
{'   &&     &&   &&.  &&  .&&  &&   ,&&%%%&&&&   '},...
{'  .&&     &&   &&.  *&& &&   &&   ,&&     &&&  '},...
{'   &&%   &&&   &&.   &&&&    &&   ,&&     ,&&  '},...
{'     &&&* &&   ,&            &&    &&      &&  '},...
{'          &&                                   '},...
{'           &                                   '},...
{' ..............................................'},...
{' ..............................................'},...
{' .....##........................,#*............'},...
{' ....(((........................#(#............'},...
{' ....(((........................#(#............'},...
{' ....(((...........(((((((((....#(#*(##((#.....'},...
{' ....(((..................((,...#((......((....'},...
{' ....(((............(#((((((*...#(#......((#...'},...
{' ....(((...........(#.....((*...#((......(((...'},...
{' ....(((*******,...((....#((*...#(##....#(#....'},...
{' ....###########....(#####(#.....#,..####......'},...
{' ..............................................'},...
