try
for ii = 1:length(umbrlla); naptime(0.02); cprintf('red','%s',umbrlla{ii}); end
catch
for ii = 1:length(umbrlla); naptime(0.02); disp(umbrlla{ii}); end
    
end
naptime(0.8);
clc;

for ii = 1:length(txt)
 
     
     if ii>9
     hrzntl(txt{ii})    
     else
     naptime(0.05); 
     disp(txt{ii})    
     end
end


fprintf('\n');


end 

function hrzntl(inp)
fprintf('%s\n',' ');
for ii=1:length(inp)

    if mod(ii,5)==0
        naptime(0.001);
    end
    
    fprintf('%s',inp(ii));
    
end

end

function pauseIf(animate, seconds)
    if animate; pause(seconds); end
end
